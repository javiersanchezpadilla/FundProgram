""" 4. B - Built-in (Incorporado)
    Es el ámbito más amplio. Son los nombres de las funciones y tipos de datos que Python tiene integrados 
    y que están disponibles automáticamente (como print, len, str, True, False, etc.)."""

print(len("Hola Mundo"))   # len es una función built-in que devuelve la longitud de una cadena
print(str(123))            # str es una función built-in que convierte un número en cadena  
print(True)                # True es un valor booleano built-in
print(False)               # False es un valor booleano built-in
